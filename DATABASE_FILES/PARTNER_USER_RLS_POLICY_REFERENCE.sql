-- ============================================================================
-- PERMISSION MAPPING TO FRONTEND
-- ============================================================================

-- Frontend expects permission objects with:
--   category: string (dashboard, campaigns, programs, tasks, wallet, users, settings)
--   level: string ('view' = read-only, 'full' = admin)

-- Partner_member permissions array should be:
-- [
--   {category: 'dashboard', level: 'view'},    → Dashboard readable
--   {category: 'campaigns', level: 'view'},    → Campaigns table readable
--   {category: 'programs', level: 'view'},     → Programs table readable
--   {category: 'tasks', level: 'view'},        → Tasks table readable
--   {category: 'wallet', level: 'view'},       → Wallets table readable
--   {category: 'users', level: 'view'},        → Profiles table readable
--   {category: 'settings', level: 'view'}      → Settings page (profile edit)
-- ]

-- All levels are 'view' because partner_members cannot perform admin operations
-- If write permissions needed in future, use level: 'write' for specific categories

