-- KEY FUNCTION: get_user_partner_id()
-- ============================================================================

-- This function is critical to all RLS policies for partner_member:

-- CREATE OR REPLACE FUNCTION public.get_user_partner_id(user_id UUID)
-- RETURNS UUID AS $$
-- BEGIN
--   RETURN (
--     SELECT partner_id FROM public.profiles 
--     WHERE id = user_id 
--     LIMIT 1
--   );
-- END;
-- $$ LANGUAGE plpgsql STABLE;

-- Usage in RLS policies:
--   partner_id = public.get_user_partner_id(auth.uid())
--
-- This compares the table's partner_id column with:
--   auth.uid() = the authenticated user's UUID (from JWT)
--   get_user_partner_id() = looks up that user's partner_id from profiles table
--
-- Result: Only rows matching the user's partner_id are returned
-- Security: Enforces partner data isolation at database level

